"""Guardrail evaluation on the red-team set (§14.4): detection, blocking, FP/FN per check.

Owner: M3.

Usage (from the project root):
    python evaluation/guardrails/run.py

Each case in evaluation/datasets/redteam_drafts.jsonl starts from the approved
TemplateOnly draft for its objective (LLMInput from tests/fixtures/contracts/) and
injects one defect: a sentence added to the body (`inject`) and/or a `mutation`:
  remove_disclaimers | replace:<old>|<new> | raw_offer_id:<id>
Writes evaluation/reports/guardrails.md.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from app.generation.clients.template_only import TemplateOnlyGenerator  # noqa: E402
from app.generation.content import DisclaimerStore, TemplateStore  # noqa: E402
from app.generation.renderer import (  # noqa: E402
    DISCLAIMER_SEPARATOR,
    SlotRenderer,
    apply_edit,
    split_disclaimers,
)
from app.guardrails.runner import GuardrailRunner  # noqa: E402
from app.schemas.enums import Objective, Severity  # noqa: E402
from app.schemas.generation import LLMInput, RenderedDraft  # noqa: E402
from app.schemas.validation import ValidationContext  # noqa: E402

DATASET = ROOT / "evaluation" / "datasets" / "redteam_drafts.jsonl"
FIXTURES = ROOT / "tests" / "fixtures" / "contracts"
REPORT = ROOT / "evaluation" / "reports" / "guardrails.md"


def load_input(objective: Objective) -> LLMInput:
    path = FIXTURES / f"llm_input_{objective.value.lower()}.json"
    return LLMInput.model_validate(json.loads(path.read_text(encoding="utf-8")))


def build_draft(case: dict, li: LLMInput, templates: TemplateStore, renderer: SlotRenderer):
    tpl = templates.for_objective(li.objective)
    raw = TemplateOnlyGenerator(templates).generate(li, tpl)
    mutation = case.get("mutation") or ""
    if mutation.startswith("raw_offer_id:"):
        raw = raw.model_copy(update={"offer_id": mutation.split(":", 1)[1]})
    draft: RenderedDraft = renderer.render(raw, li)
    subject, body = draft.subject, draft.body
    if case.get("inject"):
        main, block = split_disclaimers(body)
        parts = main.split("\n\n")
        parts.insert(2, case["inject"])
        body = "\n\n".join(parts) + (DISCLAIMER_SEPARATOR + block if block else "")
    if mutation == "remove_disclaimers":
        body = split_disclaimers(body)[0]
    elif mutation.startswith("replace:"):
        old, new = mutation.split(":", 1)[1].split("|", 1)
        body = body.replace(old, new)
    if (subject, body) != (draft.subject, draft.body):
        draft = apply_edit(draft, subject, body)
    return draft


def main() -> int:
    cases = [json.loads(line) for line in DATASET.read_text(encoding="utf-8").splitlines() if line]
    templates = TemplateStore()
    renderer = SlotRenderer(DisclaimerStore())
    runner = GuardrailRunner.default(templates)

    rows = []
    for case in cases:
        li = load_input(Objective(case["objective"]))
        draft = build_draft(case, li, templates, renderer)
        report = runner.validate(draft, ValidationContext(llm_input=li))
        fired = sorted({f.check_id for f in report.failures})
        rows.append((case, report.overall, fired))

    clean = [r for r in rows if r[0]["category"] == "clean"]
    unsafe = [r for r in rows if r[0]["expected"] == "BLOCK"]
    advisory = [r for r in rows if r[0]["expected"] == "WARN"]

    by_cat: dict[str, list[bool]] = defaultdict(list)
    for case, overall, _ in unsafe:
        by_cat[case["category"]].append(overall is Severity.BLOCK)

    fn_by_check: dict[str, list[str]] = defaultdict(list)
    tp_by_check: dict[str, int] = defaultdict(int)
    for case, _, fired in rows:
        for chk in case["expected_checks"]:
            if chk in fired:
                tp_by_check[chk] += 1
            else:
                fn_by_check[chk].append(case["id"])

    fp_cases = [r for r in clean if r[1] is Severity.BLOCK]
    blocked = sum(r[1] is Severity.BLOCK for r in unsafe)
    warned = sum(r[1] is Severity.WARN for r in advisory)
    verdict_ok = sum(r[1].value == r[0]["expected"] for r in rows)

    def pct(n: int, d: int) -> str:
        return f"{(100 * n / d):.1f}% ({n}/{d})" if d else "n/a"

    lines = [
        "# Guardrail evaluation (red-team set)",
        "",
        f"Dataset: `evaluation/datasets/redteam_drafts.jsonl` — {len(rows)} drafts "
        f"({len(unsafe)} must BLOCK, {len(advisory)} must WARN, {len(clean)} clean). "
        f"Guardrail version `{runner.version}`.",
        "Generated by `python evaluation/guardrails/run.py`. Deterministic checks only "
        "(semantic LLM-judge checks not implemented, OPEN-6).",
        "",
        "## Headline metrics (§14.4)",
        "",
        "| Metric | Result | Target [ASM] |",
        "|---|---|---|",
        f"| Unsafe message blocking | {pct(blocked, len(unsafe))} | 100% mandatory categories |",
        f"| False-positive rate (clean drafts BLOCKed) | {pct(len(fp_cases), len(clean))} "
        "| ≤ 10% |",
        f"| Advisory defects flagged WARN | {pct(warned, len(advisory))} | — |",
        f"| Exact expected verdict | {pct(verdict_ok, len(rows))} | — |",
        "",
        "## Detection by defect category",
        "",
        "| Category | Blocked |",
        "|---|---|",
        *[f"| {cat} | {pct(sum(v), len(v))} |" for cat, v in sorted(by_cat.items())],
        "",
        "## Per-check recall on expected findings",
        "",
        "| Check | Fired when expected | Missed (case ids) |",
        "|---|---|---|",
    ]
    for chk in sorted(set(tp_by_check) | set(fn_by_check)):
        total = tp_by_check[chk] + len(fn_by_check[chk])
        lines.append(
            f"| {chk} | {pct(tp_by_check[chk], total)} | {', '.join(fn_by_check[chk]) or '—'} |"
        )
    lines += [
        "",
        "## Cases with an unexpected verdict",
        "",
        "| Id | Objective | Defect | Expected | Got | Checks fired |",
        "|---|---|---|---|---|---|",
    ]
    mismatches = [r for r in rows if r[1].value != r[0]["expected"]]
    for case, overall, fired in mismatches:
        lines.append(
            f"| {case['id']} | {case['objective']} | {case['defect']} | {case['expected']} | "
            f"{overall.value} | {', '.join(fired) or '—'} |"
        )
    if not mismatches:
        lines.append("| — | | | | | |")
    lines += [
        "",
        "## Known limitations",
        "",
        "- Regex extraction misses spelled-out numbers and vague time phrases "
        '("twenty percent", "a couple of weeks").',
        "- Relative-time phrases are treated as deadlines even when benign "
        '(e.g. "this month"), which can over-block.',
        '- Unsupported claims without a number ("your favourite feature") need the '
        "semantic check, which is not implemented.",
        "- The red-team set is written by the guardrail author (M3); expect optimistic recall.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[8:16]))
    print(f"\nReport written to {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
